//! PLAN-UC-04 2.2 K-proof: the legacy material ids below the core keep their bytes.
//!
//! Sixteen sites in `oneiron-store` and `oneiron-records` moved from the store's
//! `entity_id_from_hash_material(domain, parts)` to `EntityId::derive_legacy_material`
//! under a legacy purpose, with their parts unchanged. The oracle below is a copy of the
//! base body of `entity_id_from_hash_material` and `write_hash_len`
//! (`crates/oneiron-store/src/code_snapshot/ids.rs:35-54` and `snapshot.rs:647-652` at
//! 053de8af611b), line for line.
//!
//! 1. `legacy_purposes_keep_the_base_domains`: each site's legacy purpose is BLAKE3 with
//!    its tag hashed first, and its tag is the site's domain at the base. The table is
//!    generated from the base by `gen_material_id_base_tags.py`.
//! 2. `site_ids_equal_the_base_rule`: each site's function at the head gives the oracle's
//!    id under its base domain and its base parts, over fixtures that include empty
//!    strings, no parts, a missing expected oid and every repo ref kind.
//!
//! The file lives in `oneiron-records`, the lowest crate that reaches all sixteen sites.

