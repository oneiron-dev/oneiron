// The oracle: the base body, line for line.
pub fn entity_id_from_hash_material(domain: &[u8], parts: &[&[u8]]) -> Result<EntityId> {
    for salt in 0_u64..=u64::MAX {
        let mut hasher = blake3::Hasher::new();
        hasher.update(domain);
        hasher.update(&salt.to_le_bytes());
        for part in parts {
            write_hash_len(&mut hasher, part.len())?;
            hasher.update(part);
        }
        let hash = hasher.finalize();
        let mut id = [0_u8; ENTITY_ID_LEN];
        id.copy_from_slice(&hash.as_bytes()[..ENTITY_ID_LEN]);
        if let Ok(id) = EntityId::from_bytes(id) {
            return Ok(id);
        }
    }
    Err(Error::InvariantViolation(
        "codebase deterministic entity id exhausted salt space",
    ))
}
pub fn write_hash_len(hasher: &mut blake3::Hasher, value: usize) -> Result<()> {
    let value = u64::try_from(value)
        .map_err(|_| Error::ArithmeticOverflow("codebase hash length overflow"))?;
    hasher.update(&value.to_le_bytes());
    Ok(())
}

/// The base domain of `site`, from the generated table.
fn base_domain(site: &str) -> &'static [u8] {
    BASE_TAGS
        .iter()
        .find(|(name, _, _)| *name == site)
        .map(|(_, _, domain)| *domain)
        .unwrap_or_else(|| panic!("{site} is not in BASE_TAGS"))
}

/// The oracle's id for `site` under its base domain.
fn base_id(site: &str, parts: &[&[u8]]) -> Result<EntityId> {
    entity_id_from_hash_material(base_domain(site), parts)
}

fn id(byte: u8) -> EntityId {
    EntityId::from_bytes([byte; 16]).expect("a fixture id is not reserved")
}

fn oid(hex_digit: char) -> GitOid {
    GitOid::parse_hex(hex_digit.to_string().repeat(40)).expect("a fixture oid parses")
}

const IDS: [u8; 3] = [0x01, 0x5a, 0xfe];

const TEXTS: [&str; 4] = ["", "store", "nested/path \u{fc}\u{f1}\u{1f600}", "x"];

fn hashes() -> [[u8; 32]; 3] {
    let mut counting = [0_u8; 32];
    for (at, byte) in counting.iter_mut().enumerate() {
        *byte = at as u8;
    }
    [[0_u8; 32], [0xff_u8; 32], counting]
}

