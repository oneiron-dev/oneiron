#[test]
fn legacy_purposes_keep_the_base_domains() {
    assert_eq!(BASE_TAGS.len(), 16);
    for (site, purpose, domain) in BASE_TAGS {
        assert_eq!(purpose.hash(), LegacyHash::Blake3, "{site}");
        assert_eq!(purpose.tag_mode(), TagMode::HashedFirst, "{site}");
        assert_eq!(purpose.tag().as_bytes(), *domain, "{site}");
    }
}

#[test]
fn site_ids_equal_the_base_rule() -> Result<()> {
    for hash in hashes() {
        assert_eq!(
            codebase_asset_entity_id(&hash)?,
            base_id("codebase_asset_entity_id", &[&hash])?
        );
        assert_eq!(chunk_id(&hash)?, base_id("chunk_id", &[&hash])?);
    }

    for (at, repo_ref) in repo_refs().into_iter().enumerate() {
        let snapshot = CodebaseSnapshot {
            project_id: "project".to_owned(),
            repo_ref,
            commit_hash: None,
            fork_hash: [at as u8; CODEBASE_FORK_HASH_LEN],
            scope_key: [0x70 + at as u8; CODEBASE_SCOPE_KEY_LEN],
            files: Vec::new(),
            repository: None,
        };
        assert_eq!(
            codebase_snapshot_entity_id(&snapshot)?,
            base_id(
                "codebase_snapshot_entity_id",
                &[
                    &snapshot.scope_key,
                    &snapshot.fork_hash,
                    snapshot.repo_ref.canonical().as_bytes(),
                ],
            )?
        );
    }

    for store in TEXTS {
        for init_work in TEXTS {
            assert_eq!(
                queue_aggregation_session(store, init_work)?,
                base_id(
                    "queue_aggregation_session",
                    &[store.as_bytes(), init_work.as_bytes()],
                )?
            );
            let (target, commit, tree, plan_digest) = (init_work, store, "", "plan");
            assert_eq!(
                queue_revision_id(store, init_work, target, commit, tree, plan_digest)?,
                base_id(
                    "queue_revision_id",
                    &[
                        store.as_bytes(),
                        init_work.as_bytes(),
                        target.as_bytes(),
                        commit.as_bytes(),
                        tree.as_bytes(),
                        plan_digest.as_bytes(),
                    ],
                )?
            );
        }
        assert_eq!(
            manifest_id(store)?,
            base_id("manifest_id", &[store.as_bytes()])?
        );
    }

    for byte in IDS {
        let first = id(byte);
        let second = id(byte.wrapping_add(0x11));
        assert_eq!(
            queue_provenance_id(first)?,
            base_id("queue_provenance_id", &[first.as_bytes()])?
        );
        assert_eq!(
            received_proposal_id(first)?,
            base_id("received_proposal_id", &[first.as_bytes()])?
        );
        assert_eq!(
            received_file_operation(first, second)?,
            base_id(
                "received_file_operation",
                &[first.as_bytes(), second.as_bytes()],
            )?
        );
        assert_eq!(
            birth_source_id(&first)?,
            base_id("birth_source_id", &[first.as_bytes()])?
        );
        assert_eq!(
            origin_publication_claim_id(&first)?,
            base_id("origin_publication_claim_id", &[first.as_bytes()])?
        );
        for group in hashes() {
            assert_eq!(
                workflow_filing_id(&first, &group)?,
                base_id("workflow_filing_id", &[first.as_bytes(), &group])?
            );
        }
    }

    assert_eq!(dreamer_actor_id()?, base_id("dreamer_actor_id", &[])?);
    assert_eq!(coach_actor_id()?, base_id("coach_actor_id", &[])?);
    assert_ne!(dreamer_actor_id()?, coach_actor_id()?);

    for expected in [None, Some(oid('d'))] {
        let request = publication_request(expected);
        let expected = request.expected_old_oid.as_ref().map_or("", GitOid::as_str);
        assert_eq!(
            origin_publication_id(&request)?,
            base_id(
                "origin_publication_id",
                &[
                    request.repo_id.as_bytes(),
                    request.ref_name.as_str().as_bytes(),
                    expected.as_bytes(),
                    request.new_oid.as_str().as_bytes(),
                    request.provenance_claim_id.as_bytes(),
                ],
            )?
        );
        assert_eq!(
            origin_published_commit_id(&request.new_oid)?,
            base_id(
                "origin_published_commit_id",
                &[request.new_oid.as_str().as_bytes()],
            )?
        );
    }
    Ok(())
}
