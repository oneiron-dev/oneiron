#[test]
fn purposes_derive_the_base_rule() -> Result<()> {
    let fixtures = part_fixtures();
    let mut checked = 0;
    for (site, purpose, hash, domain) in BASE_TAGS {
        if *hash != LegacyHash::Blake3 {
            continue;
        }
        for parts in &fixtures {
            let parts = slices(parts);
            assert_eq!(
                EntityId::derive_legacy_material(*purpose, &parts)?,
                entity_id_from_hash_material(domain, &parts)?,
                "{site}: {parts:?}"
            );
            assert_eq!(
                EntityId::derive_legacy_material_with_tag_suffix(*purpose, &[], &parts)?,
                entity_id_from_hash_material(domain, &parts)?,
                "{site} with an empty suffix"
            );
            checked += 1;
        }
    }
    assert!(checked >= fixtures.len() * 80, "{checked} derivations");
    Ok(())
}

#[test]
fn tag_suffix_equals_the_built_domain() -> Result<()> {
    let purpose = purposes::dispatch_byoa::SEAT_CHILD_HOLDER;
    let (_, _, _, prefix) = BASE_TAGS
        .iter()
        .find(|(site, _, _, _)| site.contains("seat_child_holder"))
        .expect("the seat child holder is in BASE_TAGS");
    let mut counting = [0_u8; 16];
    for (at, byte) in counting.iter_mut().enumerate() {
        *byte = at as u8;
    }
    for attempt in [[0_u8; 16], [0xff_u8; 16], counting] {
        for attempt_count in [0_u32, 1, 7, u32::MAX] {
            for lease_owner in ["", "runner-a", "lease \u{fc}\u{1f600}"] {
                // The base: the domain constant, then the attempt, the generation and the owner.
                let mut domain = prefix.to_vec();
                domain.extend_from_slice(&attempt);
                domain.extend_from_slice(&attempt_count.to_be_bytes());
                domain.extend_from_slice(lease_owner.as_bytes());
                // The head: the same bytes after the tag, as the suffix.
                let mut tag_suffix = attempt.to_vec();
                tag_suffix.extend_from_slice(&attempt_count.to_be_bytes());
                tag_suffix.extend_from_slice(lease_owner.as_bytes());
                assert_eq!(
                    EntityId::derive_legacy_material_with_tag_suffix(purpose, &tag_suffix, &[])?,
                    entity_id_from_hash_material(&domain, &[])?
                );
                assert_eq!(
                    [purpose.tag().as_bytes(), tag_suffix.as_slice()].concat(),
                    domain
                );
            }
        }
    }
    Ok(())
}

#[test]
fn refinement_receipt_digest_equals_the_base_sha256() {
    let purpose = purposes::skill_hub::REFINEMENT_RECEIPT_ASSET;
    let (_, _, _, domain) = BASE_TAGS
        .iter()
        .find(|(_, _, hash, _)| *hash == LegacyHash::Sha256)
        .expect("the refinement receipt is in BASE_TAGS");
    assert!(domain.ends_with(b"\0"));
    let ids = [
        [0_u8; 16],
        [0xff_u8; 16],
        [0x5a_u8; 16],
        *b"0123456789abcdef",
    ];
    for candidate in &ids {
        for ruling in &ids {
            let kept = LegacyDigest::new(purpose)
                .raw(candidate)
                .raw(ruling)
                .finish();
            assert_eq!(kept, refinement_receipt_hash(domain, candidate, ruling));
        }
    }
}
