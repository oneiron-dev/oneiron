//! K-proof (oracle) for PLAN-UC-04 stage 6.3b: the managed restore receipt id keeps its bytes.
//!
//! A verified cold restore's receipt id (`purposes::restore::RECEIPT_ID`) now starts through
//! the fingerprint crate's K door. The `verified` frame on the result pipe and every
//! `restore_status` page carry it to the supervising host, which reads it. So it must give
//! main's text for every receipt. The `base` module holds main's lines at 3db42b3bc550, copied by
//! range (the range is named above its copy; the generator is
//! `lanes/kimi/OPUS-UC04-FINGERPRINT/check/gen_keep_oracle.py`) and differing from them only
//! in indentation.
//!
//! `cargo test --locked -p oneiron-vault-contract --test fingerprint_keep_restore_receipt_id`.

use oneiron_fingerprint::{LegacyHash, TagMode, purposes};
use oneiron_vault_contract::restore::framing::receipt_id;

// Not formatted, so each copy stays line for line equal to main's.
#[rustfmt::skip]
#[allow(unreachable_pub)]
mod base {
    // main 3db42b3bc550: crates/oneiron-vault-contract/src/lib/restore/framing.rs:277-281
    /// The receipt id: BLAKE3 of its exact bytes, in lowercase hex.
    #[must_use]
    pub fn receipt_id(receipt: &[u8]) -> String {
        blake3::hash(receipt).to_hex().to_string()
    }
}

/// BLAKE3 of no bytes (the BLAKE3 specification's test vector for the empty input), the
/// id `identity_fits` sizes its widest page with.
const EMPTY_RECEIPT_ID: &str = "af1349b9f5f9a1a6a0404dea36dcc9499bcb25c9adc112b7cc9a93cae41f3262";

/// Receipts of every shape: empty, small JSON, a NUL, multi-byte text, lengths on each side
/// of BLAKE3's 64-byte block and 1024-byte chunk (and of a two-chunk tree), and 200
/// generated byte strings.
fn receipts() -> Vec<Vec<u8>> {
    let mut out: Vec<Vec<u8>> = [
        &b""[..],
        b"{}",
        br#"{"restore":"verified","checkpoint":42,"tables":["a","b"]}"#,
        b"nul \0 inside",
        "{\"note\":\"日本語 — 🦀\"}".as_bytes(),
    ]
    .into_iter()
    .map(<[u8]>::to_vec)
    .collect();
    for len in [
        1, 63, 64, 65, 1023, 1024, 1025, 2047, 2048, 2049, 4096, 65_537,
    ] {
        out.push(vec![b'r'; len]);
    }
    let mut state = 0x9e37_79b9_7f4a_7c15_u64;
    for len in 0..200_usize {
        let mut bytes = Vec::with_capacity(len * 13);
        for _ in 0..len * 13 {
            state = state
                .wrapping_mul(6_364_136_223_846_793_005)
                .wrapping_add(1_442_695_040_888_963_407);
            bytes.push((state >> 56) as u8);
        }
        out.push(bytes);
    }
    out
}

#[test]
fn the_restore_purpose_writes_no_tag() {
    let purpose = purposes::restore::RECEIPT_ID;
    assert_eq!(purpose.tag(), "oneiron.restore.receipt_id.v1");
    assert_eq!(purpose.hash(), LegacyHash::Blake3);
    assert_eq!(purpose.tag_mode(), TagMode::NotHashed);
}

#[test]
fn the_receipt_id_keeps_its_text() {
    let receipts = receipts();
    assert_eq!(receipts.len(), 217);
    for receipt in &receipts {
        let main = base::receipt_id(receipt);
        assert_eq!(main.len(), 64);
        assert_eq!(receipt_id(receipt), main, "{} bytes", receipt.len());
    }
}

#[test]
fn the_empty_receipt_keeps_blake3_s_vector() {
    assert_eq!(base::receipt_id(&[]), EMPTY_RECEIPT_ID);
    assert_eq!(receipt_id(&[]), EMPTY_RECEIPT_ID);
}
