fn detector_matches_the_myanmar_tools_compatibility_vectors() {
    for &(want, text) in COMPATIBILITY {
        let got = zawgyi_probability(text);
        if want.is_infinite() && want.is_sign_negative() {
            assert!(
                got.is_infinite() && got.is_sign_negative(),
                "row {text} should give -inf, got {got}"
            );
        } else {
            let diff = (got - want).abs();
            let tol = 1e-9 * want.abs().max(1e-300);
            assert!(
                diff <= tol || diff < 1e-12,
                "row {text} got {got}, want {want}"
            );
        }
    }
}

