//! FIX-LIST 22920 [SDK-GENERATED-HEADER-TEXT]: every generated SDK output names
//! `crates/oneiron-sdk-generator` (and the verb table), not the deleted Python
//! generator (`scripts/sdk/generate.py`, `scripts/sdk/facade_types.py`).
//! The generator runs on the repository through its public `outputs` entry.
//! `cargo test --locked -p oneiron-sdk-generator --all-features --test sdk_generated_header_text`.

use std::path::{Path, PathBuf};

/// The repository root above this crate.
fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

#[test]
fn generated_outputs_name_the_generator_crate_not_the_deleted_python_script() {
    let root = repo();
    let outputs =
        oneiron_sdk_generator::outputs(&root).expect("the generator runs on the repository");
    // No output names the deleted Python scripts.
    let mut offenders = Vec::new();
    for (path, text) in outputs.iter() {
        for deleted in ["scripts/sdk/generate.py", "scripts/sdk/facade_types.py"] {
            if text.contains(deleted) {
                offenders.push(format!("{path} names {deleted}"));
            }
        }
    }
    assert!(
        offenders.is_empty(),
        "generated outputs name the deleted Python generator: {}",
        offenders.join("; ")
    );
    // The outputs that open with a generated header name the crate that wrote them.
    let header = "// Generated by crates/oneiron-sdk-generator; edit the verb table (scripts/sdk/verbs/) instead.\n";
    let agent_verbs = outputs
        .get("packages/oneiron/src/agent-verbs.ts")
        .expect("agent-verbs.ts is an output");
    assert!(
        agent_verbs.starts_with(header),
        "agent-verbs.ts should open with the generator header, got {:?}",
        agent_verbs.lines().next().unwrap_or_default()
    );
    let facade_verbs_py = outputs
        .get("crates/oneiron-py/python/oneiron/_facade_verbs.py")
        .expect("_facade_verbs.py is an output");
    assert!(
        facade_verbs_py.starts_with(
            "# Generated by crates/oneiron-sdk-generator; edit the verb table (scripts/sdk/verbs/) instead.\n"
        ),
        "_facade_verbs.py should open with the generator header, got {:?}",
        facade_verbs_py.lines().next().unwrap_or_default()
    );
    let facade_types_ts = outputs
        .get("packages/oneiron/src/facade-types.ts")
        .expect("facade-types.ts is an output");
    assert!(
        facade_types_ts.contains(
            "// Generated by crates/oneiron-sdk-generator from the Rust types each facade row\n// of scripts/sdk/verbs/ names; edit the Rust types or the table.\n"
        ),
        "facade-types.ts should carry the TypeScript inventory header"
    );
    let facade_types_pyi = outputs
        .get("crates/oneiron-py/python/oneiron/facade_types.pyi")
        .expect("facade_types.pyi is an output");
    assert!(
        facade_types_pyi.contains(
            "\"\"\"Generated by crates/oneiron-sdk-generator from the Rust types each facade row of\nscripts/sdk/verbs/ names; edit the Rust types or the table.\n"
        ),
        "facade_types.pyi should carry the Python inventory header"
    );
    let fragment = outputs
        .get("crates/oneiron/src/verbs/generated/catalog_fragment.d.ts")
        .expect("catalog_fragment.d.ts is an output");
    assert!(
        fragment.contains(
            "// Generated by crates/oneiron-sdk-generator from scripts/sdk/verbs/ and the\n// Rust types its rows name; edit the table or the types instead.\n"
        ),
        "catalog_fragment.d.ts should carry the catalog fragment header"
    );
    let uniffi_types = outputs
        .get("crates/oneiron-uniffi/src/generated/facade_types_generated.rs")
        .expect("facade_types_generated.rs is an output");
    assert!(
        uniffi_types.starts_with(header),
        "facade_types_generated.rs should open with the generator header, got {:?}",
        uniffi_types.lines().next().unwrap_or_default()
    );
    assert!(
        uniffi_types.contains(
            "// facade type inventory (crates/oneiron-sdk-generator). Each derives serde with\n"
        ),
        "facade_types_generated.rs should name the crate for its inventory"
    );
    let revision = outputs
        .get("crates/oneiron/src/verbs/generated/catalog_fragment_revision.rs")
        .expect("catalog_fragment_revision.rs is an output");
    assert!(
        revision.starts_with(header),
        "catalog_fragment_revision.rs should open with the generator header, got {:?}",
        revision.lines().next().unwrap_or_default()
    );
}
