//! The `Python` section of `Inventory`: the declarations as the Python stubs
//! spell them (`facade_types.pyi`), and a row type as the stubs spell it outside that module.

use indexmap::IndexSet;

use super::super::reader::{find_from, next_char, word_end, word_start};
use super::super::{
    Field, Ir, Prim, RECURSION_LIMIT, RESERVED, dumps, holds, py_name, recursion_error, type_params,
};
use super::Inventory;
use crate::error::GenerateError;
use crate::py::value::Value;

/// `(hoisted, typevars, found)`: what `py_declarations` returns.
pub(crate) type PyDeclarations = (Vec<String>, IndexSet<String>, IndexSet<String>);

impl Inventory {
    /// The stubs module.
    pub(crate) fn python(&mut self, census_lines: &[String]) -> Result<String, GenerateError> {
        let erased = self.py_erased()?;
        let (hoisted, typevars, _) = self.py_declarations(&erased)?;
        let mut out = String::from(
            "\"\"\"Generated by scripts/sdk/generate.py from the Rust types each facade row of\n",
        );
        out.push_str("scripts/sdk/verbs/ names; edit the Rust types or the table.\n\n");
        out.push_str(
            "Keys are the engine's own wire spelling. Shapes the generator could not read\n",
        );
        out.push_str("are `Any`, and the census below counts them.\n\n");
        for line in census_lines {
            out.push_str(line);
            out.push('\n');
        }
        out.push_str("\"\"\"\n\n");
        out.push_str(
            "from typing import Any, Generic, Literal, NotRequired, TypedDict, TypeVar\n\n",
        );
        let mut typevars: Vec<&String> = typevars.iter().collect();
        typevars.sort();
        for name in typevars {
            out.push_str(&format!(
                "{name} = TypeVar({})\n",
                dumps(&Value::Str(name.clone()))
            ));
        }
        out.push('\n');
        for text in hoisted {
            out.push_str(&text);
        }
        Ok(out)
    }

    /// The Python names the stubs spell as a shape that
    /// takes no type arguments (FIX 5706), found to a fixed point and kept until `order` grows.
    pub(crate) fn py_erased(&mut self) -> Result<IndexSet<String>, GenerateError> {
        if self.py_erased_cache.1 != Some(self.order.len()) {
            let mut erased = IndexSet::new();
            loop {
                let (_, _, found) = self.py_declarations(&erased)?;
                if found.is_subset(&erased) {
                    break;
                }
                erased.extend(found);
            }
            self.py_erased_cache = (erased, Some(self.order.len()));
        }
        Ok(self.py_erased_cache.0.clone())
    }

    /// Every declaration as the stubs spell it,
    /// with the type variables it uses and the names it erased.
    pub(crate) fn py_declarations(
        &self,
        erased: &IndexSet<String>,
    ) -> Result<PyDeclarations, GenerateError> {
        let names = self
            .decls
            .values()
            .map(|decl| py_name(&decl.name))
            .collect();
        let mut writer = StubWriter {
            inventory: self,
            erased,
            hoisted: Vec::new(),
            typevars: IndexSet::new(),
            found: IndexSet::new(),
            names,
        };
        for key in &self.order {
            let decl = self.decl(key)?;
            let node = decl.ir()?;
            writer.typevars.extend(decl.params.iter().cloned());
            let name = py_name(&decl.name);
            let record = match node {
                Ir::Object(..) => true,
                Ir::And(members) => members
                    .iter()
                    .all(|member| matches!(member, Ir::Object(..) | Ir::Ref(..) | Ir::Partial(_))),
                _ => false,
            };
            if record {
                writer.klass(&name, node, &decl.params, &name)?;
            } else {
                let text = writer.py(node, &name)?;
                // A generic alias whose shape names none of its parameters is not generic in Python: its references
                // take no arguments.
                if !decl.params.is_empty()
                    && !decl.params.iter().any(|param| names_word(&text, param))
                {
                    writer.found.insert(name.clone());
                }
                writer.hoisted.push(format!("{name} = {text}\n"));
            }
        }
        Ok((writer.hoisted, writer.typevars, writer.found))
    }

    /// Every key a record reference holds, its own
    /// and its bases', each with its optionality (all optional under a `partial`).
    pub(crate) fn record_fields(&self, node: &Ir) -> Result<Vec<Field>, GenerateError> {
        self.record_fields_at(node, 0)
    }

    fn record_fields_at(&self, node: &Ir, depth: usize) -> Result<Vec<Field>, GenerateError> {
        if depth >= RECURSION_LIMIT {
            return Err(recursion_error());
        }
        let (partial, node) = match node {
            Ir::Partial(inner) => (true, inner.as_ref()),
            node => (false, node),
        };
        let Ir::Ref(key, _) = node else {
            return Err(not_subscriptable(node));
        };
        let ir = self.decl(key)?.ir()?;
        let members: &[Ir] = match ir {
            Ir::And(members) => members,
            ir => std::slice::from_ref(ir),
        };
        let mut fields = Vec::new();
        for member in members {
            if let Ir::Object(own, _) = member {
                fields.extend(own.iter().cloned());
            } else {
                fields.extend(self.record_fields_at(member, depth + 1)?);
            }
        }
        if partial {
            for field in &mut fields {
                field.optional = true;
            }
        }
        Ok(fields)
    }

    /// Whether a reference names a declaration Python
    /// spells as a TypedDict class.
    pub(crate) fn is_record(&self, node: &Ir) -> Result<bool, GenerateError> {
        self.is_record_at(node, 0)
    }

    fn is_record_at(&self, node: &Ir, depth: usize) -> Result<bool, GenerateError> {
        if depth >= RECURSION_LIMIT {
            return Err(recursion_error());
        }
        let node = match node {
            Ir::Partial(inner) => inner.as_ref(),
            node => node,
        };
        let Ir::Ref(key, _) = node else {
            return Ok(false);
        };
        Ok(match self.decl(key)?.ir()? {
            Ir::Object(..) => true,
            Ir::And(members) => {
                if !members
                    .iter()
                    .all(|member| matches!(member, Ir::Object(..) | Ir::Ref(..) | Ir::Partial(_)))
                {
                    return Ok(false);
                }
                for member in members {
                    if !matches!(member, Ir::Object(..)) && !self.is_record_at(member, depth + 1)? {
                        return Ok(false);
                    }
                }
                true
            }
            _ => false,
        })
    }

    /// A row type as the stubs spell it outside the
    /// declarations module; unlike the inner renderer it neither folds `| None` nor groups literals, and a shape
    /// with no name of its own is a broad dict.
    pub(crate) fn py_outer(&mut self, node: &Ir, prefix: &str) -> Result<String, GenerateError> {
        Ok(match node {
            Ir::Prim(prim, _) => prim_py(*prim).to_owned(),
            Ir::Unknown(_) | Ir::Opaque | Ir::Never => "Any".to_owned(),
            Ir::Array(inner) => format!("list[{}]", self.py_outer(inner, prefix)?),
            Ir::Option(inner) => format!("{} | None", self.py_outer(inner, prefix)?),
            Ir::Map(inner) => format!("dict[str, {}]", self.py_outer(inner, prefix)?),
            Ir::Tuple(items) => {
                let mut parts = Vec::with_capacity(items.len());
                for item in items {
                    parts.push(self.py_outer(item, prefix)?);
                }
                format!("tuple[{}]", parts.join(", "))
            }
            Ir::Union(items) => {
                let mut parts = Vec::with_capacity(items.len());
                for item in items {
                    parts.push(self.py_outer(item, prefix)?);
                }
                parts.join(" | ")
            }
            Ir::Lit(value) => format!("Literal[{}]", dumps(value)),
            Ir::Ref(key, arguments) => {
                let name = py_name(&self.decl(key)?.name);
                let arguments = if arguments.is_empty() {
                    String::new()
                } else {
                    let mut parts = Vec::with_capacity(arguments.len());
                    for argument in arguments {
                        parts.push(self.py_outer(argument, prefix)?);
                    }
                    format!("[{}]", parts.join(", "))
                };
                let erased = self.py_erased()?;
                format!(
                    "{prefix}{name}{}",
                    if erased.contains(&name) {
                        ""
                    } else {
                        arguments.as_str()
                    }
                )
            }
            _ => "dict[str, Any]".to_owned(),
        })
    }
}

/// The Python spelling of a primitive.
fn prim_py(prim: Prim) -> &'static str {
    match prim {
        Prim::String => "str",
        Prim::Int => "int",
        Prim::Float => "float",
        Prim::Bool => "bool",
        Prim::Null => "None",
    }
}

/// `self.decls[node[1]]` on a node that is no reference: callers pass only references `is_record` accepted, so
/// this is Python's lookup failure in name only.
fn not_subscriptable(node: &Ir) -> GenerateError {
    GenerateError::exception("KeyError", node.repr())
}

/// Python: `re.search(r'\b' + re.escape(param) + r'\b', text)`, for a parameter `re.match(r'\w+')`
/// read, so all word characters: an occurrence with no word character on either side.
fn names_word(text: &str, param: &str) -> bool {
    let mut from = 0;
    while let Some(at) = find_from(text, param, from) {
        if word_start(text, at) && word_end(text, at + param.len()) {
            return true;
        }
        if at >= text.len() {
            return false;
        }
        from = next_char(text, at);
    }
    false
}

/// The closures of `py_declarations` and the state they share.
struct StubWriter<'i> {
    inventory: &'i Inventory,
    erased: &'i IndexSet<String>,
    hoisted: Vec<String>,
    typevars: IndexSet<String>,
    found: IndexSet<String>,
    names: IndexSet<String>,
}

impl StubWriter<'_> {
    /// `fresh(base)`: a name no declaration takes, numbered from 2.
    fn fresh(&mut self, base: &str) -> String {
        let (mut name, mut n) = (base.to_owned(), 2);
        while self.names.contains(&name) || holds(RESERVED, &name) {
            name = format!("{base}{n}");
            n += 1;
        }
        self.names.insert(name.clone());
        name
    }

    /// `py(node, owner)`: an IR value as the stubs spell it; an object becomes a hoisted class named from `owner`.
    fn py(&mut self, node: &Ir, owner: &str) -> Result<String, GenerateError> {
        Ok(match node {
            Ir::Prim(prim, _) => prim_py(*prim).to_owned(),
            Ir::Unknown(_) | Ir::Opaque | Ir::Never => "Any".to_owned(),
            Ir::Lit(value) => format!("Literal[{}]", dumps(value)),
            Ir::Param(name) => {
                self.typevars.insert(name.clone());
                name.clone()
            }
            Ir::Array(inner) => format!("list[{}]", self.py(inner, owner)?),
            Ir::Option(inner) => {
                let inner = self.py(inner, owner)?;
                if inner.ends_with("| None") || inner == "None" {
                    inner
                } else {
                    inner + " | None"
                }
            }
            Ir::Tuple(items) => {
                let mut parts = Vec::with_capacity(items.len());
                for item in items {
                    parts.push(self.py(item, owner)?);
                }
                format!("tuple[{}]", parts.join(", "))
            }
            Ir::Map(inner) => format!("dict[str, {}]", self.py(inner, owner)?),
            Ir::Union(members) => {
                let (mut parts, mut literals): (Vec<String>, Vec<String>) =
                    (Vec::new(), Vec::new());
                for member in members {
                    if let Ir::Lit(value) = member {
                        literals.push(dumps(value));
                        continue;
                    }
                    let text = self.py(member, owner)?;
                    if !parts.contains(&text) {
                        parts.push(text);
                    }
                }
                if !literals.is_empty() {
                    parts.insert(0, format!("Literal[{}]", literals.join(", ")));
                }
                parts.join(" | ")
            }
            Ir::Partial(inner) => self.py(inner, owner)?,
            Ir::Object(..) | Ir::And(_) => {
                let hint = match node {
                    Ir::Object(_, hint) => hint.clone(),
                    Ir::And(members) => members
                        .iter()
                        .find_map(|member| match member {
                            Ir::Object(_, hint) => Some(hint.clone()),
                            _ => None,
                        })
                        .flatten(),
                    _ => None,
                };
                // `owner + (hint or 'Item')`
                let hint = hint
                    .filter(|hint| !hint.is_empty())
                    .unwrap_or_else(|| "Item".to_owned());
                let name = self.fresh(&format!("{owner}{hint}"));
                // A variant of a generic type is generic over the parameters it uses.
                let mut used: Vec<String> = type_params(node).into_iter().collect();
                used.sort();
                self.klass(&name, node, &used, owner)?;
                if !used.is_empty() && !self.found.contains(&name) {
                    format!("{name}[{}]", used.join(", "))
                } else {
                    name
                }
            }
            Ir::Ref(key, arguments) => {
                let decl = self.inventory.decl(key)?;
                let arguments = if arguments.is_empty() {
                    String::new()
                } else {
                    let mut parts = Vec::with_capacity(arguments.len());
                    for argument in arguments {
                        parts.push(self.py(argument, owner)?);
                    }
                    format!("[{}]", parts.join(", "))
                };
                let name = py_name(&decl.name);
                let bare = self.erased.contains(&name) || self.found.contains(&name);
                format!("{name}{}", if bare { "" } else { arguments.as_str() })
            }
        })
        // Every IR kind has its arm, so the Python fallthrough (`raise ValueError(node)`) has no port.
    }

    /// `klass(name, node, params, owner)`: a TypedDict for an object (or an
    /// intersection of objects), or an alias when a dict cannot say it.
    fn klass(
        &mut self,
        name: &str,
        node: &Ir,
        params: &[String],
        owner: &str,
    ) -> Result<(), GenerateError> {
        let members: &[Ir] = match node {
            Ir::And(members) => members,
            node => std::slice::from_ref(node),
        };
        let (mut bases, mut fields): (Vec<String>, Vec<Field>) = (Vec::new(), Vec::new());
        for member in members {
            match member {
                Ir::Object(own, _) => fields.extend(own.iter().cloned()),
                // A flattened optional record (TypeScript's `Partial<T>`) adds its keys as NotRequired ones, never
                // as a base whose keys a TypedDict would require (FIX 6555).
                Ir::Partial(inner)
                    if matches!(inner.as_ref(), Ir::Ref(_, arguments) if arguments.is_empty())
                        && self.inventory.is_record(inner)? =>
                {
                    for field in self.inventory.record_fields(inner)? {
                        fields.push(Field {
                            optional: true,
                            ..field
                        });
                    }
                }
                Ir::Partial(inner)
                    if matches!(inner.as_ref(), Ir::Ref(..))
                        && self.inventory.is_record(inner)? =>
                {
                    bases.push(self.py(inner, owner)?);
                }
                Ir::Ref(..) if self.inventory.is_record(member)? => {
                    bases.push(self.py(member, owner)?);
                }
                _ => {
                    self.hoisted.push(format!("{name} = dict[str, Any]\n"));
                    self.found.insert(name.to_owned());
                    return Ok(());
                }
            }
        }
        let generic = if params.is_empty() {
            String::new()
        } else {
            format!(", Generic[{}]", params.join(", "))
        };
        let mut rows: Vec<(Value, String)> = Vec::with_capacity(fields.len());
        for field in &fields {
            let text = self.py(&field.value, owner)?;
            rows.push((
                field.key.clone(),
                if field.optional {
                    format!("NotRequired[{text}]")
                } else {
                    text
                },
            ));
        }
        let mut functional = false;
        for (key, _) in &rows {
            let Value::Str(key) = key else {
                return Err(GenerateError::attribute(key.type_name(), "isidentifier"));
            };
            if !crate::py::text::isidentifier(key) || crate::py::builtins::is_keyword(key) {
                functional = true;
                break;
            }
        }
        if functional {
            if !bases.is_empty() || !params.is_empty() {
                self.hoisted.push(format!("{name} = dict[str, Any]\n"));
                self.found.insert(name.to_owned());
                return Ok(());
            }
            let body = rows
                .iter()
                .map(|(key, text)| format!("{}: {text}", dumps(key)))
                .collect::<Vec<_>>()
                .join(", ");
            self.hoisted.push(format!(
                "{name} = TypedDict({}, {{{body}}})\n",
                dumps(&Value::Str(name.to_owned()))
            ));
            return Ok(());
        }
        let bases = if bases.is_empty() {
            "TypedDict".to_owned()
        } else {
            bases.join(", ")
        };
        let mut class = format!("class {name}({bases}{generic}):\n");
        if rows.is_empty() {
            class.push_str("    ...\n");
        }
        for (key, text) in &rows {
            if let Value::Str(key) = key {
                class.push_str(&format!("    {key}: {text}\n"));
            }
        }
        self.hoisted.push(class);
        Ok(())
    }
}
