impl Generator {
    /// Port of generate.py:335-337 (mcp_rows): the rows the MCP doors serve as tools, every row but a browser row.
    pub(crate) fn mcp_rows(&self) -> Vec<RowId> {
        self.callable_rows
            .iter()
            .copied()
            .filter(|&id| {
                !self.rows[id]
                    .get("mcp")
                    .is_some_and(|mcp| mcp.is_str("none"))
            })
            .collect()
    }
}
