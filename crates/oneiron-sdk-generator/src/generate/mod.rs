/// A row object in the `RowStore`: Python's sets share row objects, so a set holds ids.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) struct RowId(pub(crate) usize);

/// Every row object: the verb rows first (file-name order), then the synthetic host rows in the order Python makes
/// them (`ROWS`'s, then `BOARD_HOST_ROWS`'s). A mutation through the store is seen by every set, as in Python.
#[derive(Debug, Default)]
pub(crate) struct RowStore {
    rows: Vec<Dict>,
}

impl RowStore {
    /// A new row object.
    pub(crate) fn push(&mut self, row: Dict) -> RowId {
        self.rows.push(row);
        RowId(self.rows.len() - 1)
    }

    /// The row object `id`, to change in place.
    pub(crate) fn get_mut(&mut self, id: RowId) -> &mut Dict {
        &mut self.rows[id.0]
    }

    /// The rows of a set, in its order.
    pub(crate) fn select(&self, ids: &[RowId]) -> Vec<&Dict> {
        ids.iter().map(|&id| &self[id]).collect()
    }
}

impl Index<RowId> for RowStore {
    type Output = Dict;

    fn index(&self, id: RowId) -> &Dict {
        &self.rows[id.0]
    }
}

/// The Python generator's module globals: one field per module-level row set, Python's name in snake case.
#[derive(Debug)]
pub(crate) struct Generator {
    /// `ROOT`: the repository root, resolved.
    pub(crate) root: PathBuf,
    /// `hand_declared`'s `functools.cache`, by language.
    pub(crate) hand_declared_cache: common::HandDeclaredCache,
    /// Every row object the sets below share.
    pub(crate) rows: RowStore,
    /// `MANIFEST['verbs']`.
    pub(crate) manifest: Vec<RowId>,
    /// `HOST_ROWS`.
    pub(crate) host_rows: Vec<RowId>,
    /// `HOST_RUN_ROWS`.
    pub(crate) host_run_rows: Vec<RowId>,
    /// `HOST_BROWSER_ROWS`.
    pub(crate) host_browser_rows: Vec<RowId>,
    /// `HOST_BOARD_ROWS`.
    pub(crate) host_board_rows: Vec<RowId>,
    /// `BROWSER_ROWS`.
    pub(crate) browser_rows: Vec<RowId>,
    /// `ROWS` (named apart from `rows`, the store): the callable rows but the original host-browser ones, then the
    /// non-board host projections.
    pub(crate) callable_rows: Vec<RowId>,
    /// `BOARD_HOST_ROWS`.
    pub(crate) board_host_rows: Vec<RowId>,
    /// `BOARD_HOST_NAMES`, a set: first-seen order, equal names (`1`, `1.0`, `True`) kept once. Python iterates a set
    /// in hash order, so a reader tests membership or sorts.
    pub(crate) board_host_names: Vec<Value>,
    /// `DEFINITIONS`.
    pub(crate) definitions: Vec<RowId>,
    /// `RUN_ROWS`.
    pub(crate) run_rows: Vec<RowId>,
    /// `CODE_MODE_ROWS`.
    pub(crate) code_mode_rows: Vec<RowId>,
    /// `SCHEMA_ROWS`.
    pub(crate) schema_rows: Vec<RowId>,
    /// `FACADE_ROWS`.
    pub(crate) facade_rows: Vec<RowId>,
    /// `TYPE_NAMES` (read once, where the Python generator imported `facade_types`): every `Inventory` is built over
    /// it, as catalog_fragment's second one reads the same module global.
    pub(crate) type_names: Value,
    /// `INVENTORY`. `None` only from `Generator::rows_only` (the refusal tests' module level, without the type
    /// inventory); the emitters run on `Generator::new`'s.
    pub(crate) inventory: Option<Inventory>,
    /// The crate source files the catalog fragment's own inventory read (its index's dependency set, as paths from
    /// the repository root), set by `outputs()`; `Generator::dependencies` joins it to `INVENTORY`'s.
    pub(crate) fragment_dependencies: BTreeSet<String>,
}

impl Generator {
    /// The rows the MCP doors serve as tools, every row but a browser row.
    pub(crate) fn mcp_rows(&self) -> Vec<RowId> {
        self.callable_rows
            .iter()
            .copied()
            .filter(|&id| {
                !self.rows[id]
                    .get("mcp")
                    .is_some_and(|mcp| mcp.is_str("none"))
            })
            .collect()
    }
}
