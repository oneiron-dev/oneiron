/// The class the registry gives the entity kind `kind`, when it names it.
pub(super) fn kind_class(kind: &str) -> Option<Class> {
    KINDS
        .iter()
        .find(|(_, kinds)| kinds.contains(&kind))
        .map(|(class, _)| *class)
}

/// A family's identity: its database and prefix.
fn identity(decl: &SideTableDecl) -> (bool, &'static [u8]) {
    (decl.db == SideDb::SyncState, decl.prefix)
}

fn db_name(db: SideDb) -> &'static str {
    match db {
        SideDb::VaultMeta => "vault_meta",
        SideDb::SyncState => "sync_state",
    }
}

fn incomplete(what: &'static str) -> Error {
    Error::InvariantViolation(what)
}

/// Refuses unless the registry names every declared family once and no
/// family that is not declared, every manifest database once and every
/// entity kind once, and unless each not-imaged family is one tier
/// filtering leaves out whole. Only an enabled capture runs it.
pub(super) fn check() -> Result<()> {
    let mut named = BTreeSet::new();
    for (class, decls) in FAMILIES {
        for decl in *decls {
            if !named.insert(identity(decl)) {
                return Err(incomplete("a checkpoint payload family is named twice"));
            }
            if *class == Class::NotImaged
                && storage_tier(db_name(decl.db), decl.prefix) == StorageTier::Canonical
            {
                return Err(incomplete("a not-imaged payload family is canonical"));
            }
        }
    }
    let declared: BTreeSet<_> = side_table::declared().map(identity).collect();
    if named != declared {
        return Err(incomplete(
            "the checkpoint payload registry does not name every declared family",
        ));
    }
    let databases: BTreeSet<&str> = DATABASES.iter().map(|(name, _)| *name).collect();
    if databases.len() != DATABASES.len()
        || databases
            != DB_MANIFEST
                .iter()
                .map(|entry| entry.name)
                .collect::<BTreeSet<_>>()
    {
        return Err(incomplete(
            "the checkpoint payload registry does not name every database",
        ));
    }
    let kinds: Vec<&str> = KINDS
        .iter()
        .flat_map(|(_, kinds)| kinds.iter().copied())
        .collect();
    let registered: BTreeSet<&str> = kinds.iter().copied().collect();
    if registered.len() != kinds.len()
        || registered
            != ENTITY_TYPE_REGISTRY
                .iter()
                .map(|entry| entry.kind)
                .collect::<BTreeSet<_>>()
    {
        return Err(incomplete(
            "the checkpoint payload registry does not name every entity kind",
        ));
    }
    Ok(())
}

/// The class of one image row of `database`: `declared`, its family's or
/// its database's, save in the two mixed families whose rows hold responses
/// one by one (FIX 9179): a queue row and a wait index row the response
/// client takes, by the same family and scan the census reads (a response,
/// the erased marker, a wait's erased reply), go to it; every other row of
/// theirs stays as declared, unclassified and named on the receipt.
pub(super) fn class_for_row(database: &str, key: &[u8], value: &[u8], declared: Class) -> Class {
    let mixed = match database {
        "job_records" => true,
        "vault_meta" => key.starts_with(side_table::CODE_RUN_WAIT_INDEX.prefix),
        _ => false,
    };
    let response = mixed
        && ResponseDb::of_name(database)
            .and_then(|db| ResponseFamily::of_row(db, key, value))
            .is_some_and(|family| family.placed_as_response(key, value));
    if response {
        Class::Other(Client::Dispatch(OtherClient::Response))
    } else {
        declared
    }
}

/// The registry's families by database and prefix, to find a row's.
pub(super) struct Families([BTreeMap<&'static [u8], (&'static SideTableDecl, Class)>; 2]);

impl Families {
    pub(super) fn new() -> Self {
        let mut by_db = [BTreeMap::new(), BTreeMap::new()];
        for (class, decls) in FAMILIES {
            for decl in *decls {
                let (sync, prefix) = identity(decl);
                by_db[usize::from(sync)].insert(prefix, (*decl, *class));
            }
        }
        Self(by_db)
    }

    /// The family the row `key` of `db` falls under, if one is declared:
    /// the last prefix at or before `key`, the only one it can start with
    /// since declared prefixes are disjoint.
    pub(super) fn of(&self, db: SideDb, key: &[u8]) -> Option<(&'static SideTableDecl, Class)> {
        self.0[usize::from(db == SideDb::SyncState)]
            .range::<[u8], _>((Bound::Unbounded, Bound::Included(key)))
            .next_back()
            .filter(|(prefix, _)| key.starts_with(prefix))
            .map(|(_, family)| *family)
    }
}
