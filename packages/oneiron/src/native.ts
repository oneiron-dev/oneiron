/**
 * The private native binding seam.
 *
 * This module is NOT part of the package's public surface: `src/index.ts` is
 * the only export entry, and it re-exports `Oneiron` and `OneironError` only.
 * `NativeClient` is held by the wrapper and never handed out, which is what
 * keeps `VaultBridge`, `ActorScopedVault`, and every other raw native class
 * out of the flagship package.
 *
 * There is deliberately no HTTP client here or anywhere else in this package.
 * `connect()` reaches `oneiron-server` through the one Rust stack owned by
 * `oneiron-remote`, so JavaScript never holds a URL, a timeout, or a route.
 */

import { createRequire } from "node:module"

import type {
  CheckpointPin,
  EngineReply,
  EngineRequest,
  HostRootProfile,
  NativeLimitQuestion,
} from "./types.js"
import type { CommReach } from "./facade-types.js"
import type { NativeAgentVerbs } from "./native-verbs.js"

/** The native class's shape, as generated by napi-rs; its verb methods are generated from the verb table (native-verbs.ts). */
export interface NativeClient extends NativeAgentVerbs {
  asActor(actorKey: string): NativeClient
  inRoomTurn(roomRef: string): NativeClient
  inOffRecordSession(sessionRef: string): NativeClient
  withReadCredential(credential: string): NativeClient
  lastReceiptRef(): string | null
  lastHookNotice(): string | null
  /** What `openWithHostRoot` did with its root; `null` on every other handle. */
  hostRootProfile(): HostRootProfile | null
  /** The engine-limit crossings this client's own vault kept; `null` on a remote, attached, or rebound view. */
  nativeLimitQuestions(): NativeLimitQuestion[] | null
  retry(pending: unknown, verb: string, input: unknown): unknown
  lensFrameEvent(cardId: string, request: unknown): unknown
  closeLensFrame(cardId: string): unknown
  exportTo(path: string, format: string | undefined): unknown
}

/** The static half napi-rs generates for a `#[napi(factory)]` constructor. */
interface NativeClientConstructor {
  /** `deviceClass` is the host's declaration, `"computer"` when omitted (FIX 5560). */
  open(
    path: string | undefined,
    dimensions: number | undefined,
    deviceClass: string | undefined,
  ): NativeClient
  /** `open`, then this install's machine profile from the host root's exact bytes (FIX 4730). */
  openWithHostRoot(
    path: string | undefined,
    dimensions: number | undefined,
    hostRootSecret: Uint8Array,
    deviceClass: string | undefined,
    holdCheckpointRootSigner: boolean | undefined,
  ): NativeClient
  connect(url: string, key: string): NativeClient
  /** `pin` is absent when the vault has no attested checkpoint. */
  pair(link: string): { url: string; credential: string; pin?: CheckpointPin; comm: CommReach }
}

/** What `NativeEngine.start` takes besides the path (OF-237). */
export interface NativeEngineOptions {
  dimensions?: number
  configFile?: string
  secrets?: Record<string, string>
  memoryBytes?: number
  cpuMillisPerSecond?: number
}

/** A connection the app holds to its engine's server (FIX 4895). */
export interface NativeEngineConnection {
  send(bytes: Uint8Array): void
  receive(): Uint8Array
  close(): void
}

/** The engine-backed served client's native half, present only in an `engine` build. */
export interface NativeEngine {
  client(key: string): NativeClient
  localClient(): NativeClient
  request(request: EngineRequest): EngineReply
  requestArtifact(request: EngineRequest): EngineReply
  connect(): NativeEngineConnection
  connectArtifact(): NativeEngineConnection
  wake(): void
  stop(): void
  close(): void
}

/** The static half of `NativeEngine`. */
interface NativeEngineConstructor {
  start(path: string, options: NativeEngineOptions | undefined): NativeEngine
}

interface NativeBinding {
  NativeClient: NativeClientConstructor
  /** Absent unless the addon was built with the `engine` cargo feature. */
  NativeEngine?: NativeEngineConstructor
}

// napi-rs emits a CommonJS loader that picks the right prebuilt `.node`
// artifact for the running platform, so it is `require`d rather than imported:
// the selection is a runtime decision this package must not try to make in a
// static import specifier.
const require = createRequire(import.meta.url)
const binding = require("../native/index.cjs") as NativeBinding

export const NativeClient: NativeClientConstructor = binding.NativeClient

/** `undefined` unless the addon was built with the `engine` cargo feature. */
export const NativeEngine: NativeEngineConstructor | undefined = binding.NativeEngine
