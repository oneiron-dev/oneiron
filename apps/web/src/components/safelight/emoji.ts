/* the words match on any part; an empty query shows the first rows */
export function searchEmoji(q: string, limit = 32): Array<[string, string]> {
  const s = q.trim().toLowerCase()
  if (!s) return EMOJI.slice(0, limit)
  const words = s.split(/\s+/)
  return EMOJI.filter(([, name]) => words.every((w) => name.includes(w))).slice(0, limit)
}
