def cell(text: str) -> str:
    return text.replace("|", "\\|") if text else "—"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell(c) for c in row) + " |")
    return out


def surface_text(surface: dict) -> str:
    if not surface:
        return "—"
    return " · ".join(f"{n} {k}" for k, n in surface.items())


def notable_text(names: list[str]) -> str:
    if not names:
        return "—"
    shown = names[:NOTABLE_MAX]
    rest = len(names) - len(shown)
    return ", ".join(shown) + (f" +{rest}" if rest else "")


def yes(flag: bool) -> str:
    return "yes" if flag else "—"


def legend_lines() -> list[str]:
    return [
        "Size buckets are line counts of the whole file: `s` < 300 · `m` 300–799 · "
        "`L` 800–1499 · `XL` ≥ 1500.",
        "`L` or `XL` on a non-test file means the file is over the 800-line ratchet bar "
        "(`scripts/ratchet/check.sh`); split it, do not grow it.",
    ]


def render_top(data: dict) -> str:
    crates = data["crates"]
    lines = [
        "# Code map",
        "",
        "Orientation map of Rust crates under `crates/`: one row per crate, then one table "
        "per crate at the top-level-module grain.",
        "Scope excludes `heed`, `vendor/`, and `target/`. Other workspace members, including "
        "[oneiron-macos](../apps/macos/src-tauri/), are not indexed here.",
        "Read this overview first, then search `codemap/<crate>.md` by module path or type "
        "for the per-file table (kind, size bucket, pub surface, notable types). "
        "Do not load large crate maps, especially `codemap/oneiron.md`, in full.",
        "To find code by capability, grep `codemap/BY-CAPABILITY.md` (reviewed aliases, then "
        "every module's purpose with its entry path); for an OF or ARCH id, grep "
        "`codemap/BY-SPEC.md`.",
        f"Generated by `{GENERATOR}` — never edit by hand.",
        "Regenerated on main by `.github/workflows/codemap.yml`; PRs never touch it; "
        "run the generator locally only to read a fresh map.",
        "`--sizes` prints the live line-count table (never committed).",
        "Test files follow the ratchet definition: a `tests/` or `tests_*/` directory, "
        "`tests.rs`, `*_tests.rs` or `tests_*.rs`.",
        *legend_lines(),
        "",
        "## Workspace",
        "",
    ]
    rows = []
    for name, crate in crates.items():
        rows.append(
            [
                f"[{name}](codemap/{name}.md)",
                crate["purpose"],
                str(crate["source_files"]),
                str(crate["test_files"]),
                str(crate["over_bar"]),
            ]
        )
    lines += table(["crate", "purpose", "source files", "test files", "over 800-line bar"], rows)
    for name, crate in crates.items():
        lines += ["", f"## {name}", ""]
        with_vault = crate["has_impl_vault"]
        header = ["module", "layout", "files", "largest src bucket"]
        if with_vault:
            header.append("impl Vault")
        header.append("purpose")
        rows = []
        for mod_name, mod in crate["modules"].items():
            row = [
                f"`{mod_name}`",
                mod["layout"],
                str(mod["files"]),
                mod["largest_src_bucket"],
            ]
            if with_vault:
                row.append(yes(mod["impl_vault"]))
            row.append(mod["purpose"])
            rows.append(row)
        lines += table(header, rows)
    return "\n".join(lines) + "\n"


def render_crate(name: str, crate: dict) -> str:
    lines = [
        f"# {name}",
        "",
        f"{crate['purpose']}",
        "",
        GENERATED_PAGE_NOTE,
        *legend_lines(),
        "`pub(crate)` / `pub(super)` items are counted under `crate-vis`; `pub use` under "
        "`re-export`. Notable types are `pub` structs, enums and traits.",
        "",
        "## Files",
        "",
    ]
    rows = []
    for f in crate["files"]:
        rows.append(
            [
                f"`{f['path']}`",
                f["kind"],
                "generated" if f["generated"] else f["bucket"],
                surface_text(f["surface"]),
                notable_text(f["notable"]),
                f["purpose"],
            ]
        )
    lines += table(["path", "kind", "bucket", "pub surface", "notable types", "purpose"], rows)
    return "\n".join(lines) + "\n"


def render_json(data: dict) -> str:
    out: dict = {"crates": {}}
    for name, crate in data["crates"].items():
        out["crates"][name] = {
            "purpose": crate["purpose"],
            "source_files": crate["source_files"],
            "test_files": crate["test_files"],
            "over_bar": crate["over_bar"],
            "modules": {
                mod_name: {
                    "layout": mod["layout"],
                    "entry": mod["entry"],
                    "files": mod["files"],
                    "largest_src_bucket": mod["largest_src_bucket"],
                    "impl_vault": mod["impl_vault"],
                    "purpose": mod["purpose"],
                    "spec_ids": mod["spec_ids"],
                }
                for mod_name, mod in crate["modules"].items()
            },
            "files": [
                {
                    "path": f["path"],
                    "kind": f["kind"],
                    "bucket": f["bucket"],
                    "surface": f["surface"],
                    "notable": f["notable"],
                    "purpose": f["purpose"],
                }
                for f in crate["files"]
            ],
        }
    return json.dumps(out, sort_keys=True, indent=1, ensure_ascii=False) + "\n"


def file_index(data: dict) -> dict[str, dict]:
    """Every mapped file by its repo-relative path, in map order."""
    return {
        f"crates/{name}/{f['path']}": f
        for name, crate in data["crates"].items()
        for f in crate["files"]
    }


def file_bucket(f: dict) -> str:
    return "generated" if f["generated"] else f["bucket"]


def render_spec_index(data: dict) -> str:
    rows_by_id: dict[str, list[list[str]]] = {}
    for path, f in file_index(data).items():
        if f["kind"] != "src":
            continue
        for spec_id in f["spec_ids"]:
            rows_by_id.setdefault(spec_id, []).append([spec_id, f"`{path}`", file_bucket(f)])
    lines = [
        "# Code by spec ID",
        "",
        "Every OF and ARCH id that the leading `//!` doc block of a non-test source file names, "
        "with its part suffix and any family prefix (`OF-498c`, `CROSS-ARCH-0019`, "
        "`EIRI-ARCH-0002`), one row per id and file. Grep it: "
        "`rg -n 'OF-575' docs/codemap/BY-SPEC.md`.",
        "Paths are repo-relative. A row is a pointer the file itself states, not proof of "
        "ownership or status. An id with no row is not absent: search the source too "
        "(`git grep -n 'OF-575' -- crates`).",
        "FIX numbers are FIX-LIST rows, not spec ids, and are not indexed here.",
        GENERATED_PAGE_NOTE,
        legend_lines()[0],
        "",
    ]
    rows = [row for spec_id in sorted(rows_by_id, key=spec_sort_key) for row in rows_by_id[spec_id]]
    lines += table(["spec ID", "file", "bucket"], rows)
    return "\n".join(lines) + "\n"


def render_capability_index(
    root: Path, data: dict, aliases: list[dict], unplaced: list[str]
) -> tuple[str, list[str]]:
    """The capability page, and each alias path that names no file in the repo.

    A mapped path shows its size bucket; a file outside the map (a pack's
    Markdown, a script's README) shows `outside the map`.
    """
    files = file_index(data)
    missing: list[str] = []
    alias_rows = []
    for entry in aliases:
        shown = []
        for path in entry["paths"]:
            info = files.get(path)
            if info is not None:
                shown.append(f"`{path}` ({file_bucket(info)})")
            elif (root / path).is_file():
                shown.append(f"`{path}` (outside the map)")
            else:
                missing.append(
                    f"{ALIASES_PATH}:{entry['line']}: {path} is not a file in the repo "
                    f"(moved or deleted?), in {entry['phrase']!r}"
                )
                shown.append(f"`{path}` (MISSING: fix it in `{ALIASES_PATH}`)")
        alias_rows.append(
            [
                entry["phrase"],
                "; ".join(entry["synonyms"]),
                "; ".join(shown),
                "; ".join(entry["spec_ids"]),
                entry["note"],
            ]
        )
    module_rows = []
    for name, crate in data["crates"].items():
        for mod_name, mod in crate["modules"].items():
            entry_path = mod["entry"] or f"crates/{name}/src/{mod_name}/"
            module_rows.append(
                [
                    mod["purpose"],
                    f"`{entry_path}`",
                    mod["largest_src_bucket"],
                    ", ".join(mod["spec_ids"]),
                ]
            )
    lines = [
        "# Code by capability",
        "",
        "Grep this page for a capability in plain words or a synonym, ignoring case: "
        "`rg -n -i 'enrol' docs/codemap/BY-CAPABILITY.md`.",
        "Then open the listed source and follow its entry point and callers before you describe "
        "what runs.",
        "A miss here is not absence: search `docs/codemap/*.md` and the source, and report "
        "\"not located\" with the ref, the terms and the scope.",
        GENERATED_PAGE_NOTE,
        legend_lines()[0],
        "",
        "## Reviewed aliases",
        "",
        f"The capabilities in `{ALIASES_PATH}`, one row each: its synonyms, its owning files "
        "with their size bucket, the spec IDs those files' docs name, and what it is and is not. "
        "Add a row there when a capability is hard to find by the words its code uses, and fix "
        "a row when you move or delete a file it names.",
        "",
    ]
    lines += table(["capability", "synonyms", "files", "spec IDs", "note"], alias_rows)
    if unplaced:
        lines += [
            "",
            "## Not located",
            "",
            "Capabilities the alias review searched for and could not place, with the terms it "
            "tried. Report them as not located; do not name an owner for them.",
            "",
            *(f"- {item}" for item in unplaced),
        ]
    lines += [
        "",
        "## Modules by purpose",
        "",
        "Every top-level module of every mapped crate: its purpose, its entry file (its directory "
        "when it has no seam file), its largest non-test file bucket, and the OF and ARCH ids its "
        "entry file's leading doc block names. For file rows, grep `docs/codemap/<crate>.md`.",
        "",
    ]
    lines += table(["purpose", "module entry", "largest src bucket", "spec IDs"], module_rows)
    return "\n".join(lines) + "\n", missing


def render_artifacts(
    root: Path, data: dict, aliases: list[dict], unplaced: list[str]
) -> tuple[dict[PurePosixPath, bytes], list[str]]:
    """Every artifact's bytes, and each alias path that names no file in the repo."""
    artifacts = {MAP_PATH: render_top(data).encode("utf-8")}
    for name, crate in data["crates"].items():
        artifacts[DIR_PATH / f"{name}.md"] = render_crate(name, crate).encode("utf-8")
    artifacts[JSON_PATH] = render_json(data).encode("utf-8")
    artifacts[SPEC_PATH] = render_spec_index(data).encode("utf-8")
    capability_page, missing = render_capability_index(root, data, aliases, unplaced)
    artifacts[CAPABILITY_PATH] = capability_page.encode("utf-8")
    return artifacts, missing


def table_cells(line: str) -> list[str] | None:
    """The stripped cells of a Markdown table row `| a | b |`, or None for any other line."""
    row = line.strip()
    if len(row) < 2 or not (row.startswith("|") and row.endswith("|")):
        return None
    return [cell.strip() for cell in row[1:-1].split("|")]


def alias_list(text: str, where: str, column: str) -> list[str]:
    """A `; `-separated list cell.  An empty cell is an empty list; an empty item fails."""
    if not text:
        return []
    items = [item.strip() for item in text.split(";")]
    if not all(items):
        raise CodemapError(f"{where}: {column} has an empty item; separate items with `; `")
    return items


def check_alias_path(path: str, where: str) -> None:
    """Fail unless `path` is one repo-relative file path in its one canonical spelling.

    `PurePosixPath` drops `.` parts, repeated slashes and a trailing slash, so
    `./crates/x.rs`, `crates//x.rs` and `crates/x.rs/` all fail: every accepted
    path is spelled exactly as the map spells it, and a repeated path is always a
    repeated string.
    """
    parts = PurePosixPath(path).parts
    if (
        not parts
        or path.startswith("/")
        or "\\" in path
        or ".." in parts
        or any(c.isspace() for c in path)
    ):
        raise CodemapError(f"{where}: {path!r} is not a repo-relative file path")
    canonical = str(PurePosixPath(path))
    if canonical != path:
        raise CodemapError(f"{where}: write the path {path!r} as {canonical!r}")


def load_aliases(root: Path) -> tuple[list[dict], list[str]]:
    """The reviewed capability aliases and the phrases the review could not place.

    The file has three parts, in order: free prose (a title and notes, with no `|`),
    exactly one table with the header `| phrase | synonyms | paths | spec_ids | note |`,
    its separator row and one row of five cells per capability, and after the table
    only blank lines and an optional `## Phrases not placed` heading followed by
    one-line `- ` bullets.  Every other line fails closed: a row that lost its opening
    or closing `|` (it ends the table, so it is a line after the table), any heading or
    prose after the table, a `|` in the prose, a missing or renamed column, an extra
    cell, an empty phrase, note or path list, an empty list item, a path that is not
    repo-relative in its canonical spelling and a repeated phrase or path.
    """
    rel = ALIASES_PATH
    try:
        text = (root / rel).read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError) as error:
        raise CodemapError(f"unreadable alias file {rel}: {error}") from error
    lines = text.split("\n")
    header = list(ALIAS_COLUMNS)
    starts = [i for i, line in enumerate(lines) if table_cells(line) == header]
    if len(starts) != 1:
        raise CodemapError(
            f"{rel}: needs exactly one alias table with the header | {' | '.join(header)} |"
        )
    start = starts[0]
    separator = table_cells(lines[start + 1]) if start + 1 < len(lines) else None
    if (
        separator is None
        or len(separator) != len(header)
        or not all(TABLE_SEPARATOR_CELL_RE.fullmatch(c) for c in separator)
    ):
        raise CodemapError(f"{rel}:{start + 2}: the table header needs its `| --- |` separator row")
    end = start + 2
    while end < len(lines) and table_cells(lines[end]) is not None:
        end += 1
    for i in range(start):
        if "|" in lines[i]:
            raise CodemapError(
                f"{rel}:{i + 1}: a `|` before the alias table; only prose may precede the table"
            )
        if lines[i].rstrip() == ALIAS_UNPLACED_HEADING:
            raise CodemapError(f"{rel}:{i + 1}: {ALIAS_UNPLACED_HEADING!r} must follow the table")
    entries: list[dict] = []
    phrases: set[str] = set()
    for i in range(start + 2, end):
        where = f"{rel}:{i + 1}"
        cells = table_cells(lines[i])
        if len(cells) != len(header):
            raise CodemapError(
                f"{where}: a row has exactly {len(header)} cells ({', '.join(header)}); "
                "a `|` inside a cell is not supported"
            )
        entry: dict = {"line": i + 1}
        for column, value in zip(ALIAS_COLUMNS, cells):
            if column in ALIAS_LIST_COLUMNS:
                entry[column] = alias_list(value, where, column)
            elif not value:
                raise CodemapError(f"{where}: {column} must not be empty")
            else:
                entry[column] = value
        if not entry["paths"]:
            raise CodemapError(f"{where}: paths must name at least one file")
        for path in entry["paths"]:
            check_alias_path(path, where)
        if len(set(entry["paths"])) != len(entry["paths"]):
            raise CodemapError(f"{where}: a path is listed twice")
        key = entry["phrase"].casefold()
        if key in phrases:
            raise CodemapError(f"{where}: duplicate phrase {entry['phrase']!r}")
        phrases.add(key)
        entries.append(entry)
    if not entries:
        raise CodemapError(f"{rel}: the alias table has no rows")
    unplaced: list[str] = []
    in_unplaced = False
    for i in range(end, len(lines)):
        line = lines[i].rstrip()
        where = f"{rel}:{i + 1}"
        if not line:
            continue
        if line == ALIAS_UNPLACED_HEADING and not in_unplaced:
            in_unplaced = True
        elif in_unplaced and line.startswith("- ") and line[2:].strip():
            unplaced.append(line[2:].strip())
        elif "|" in line and not in_unplaced:
            raise CodemapError(
                f"{where}: a table row outside the alias table; every row starts and ends "
                "with `|`, and the table has no blank line"
            )
        elif in_unplaced:
            raise CodemapError(f"{where}: each line under {ALIAS_UNPLACED_HEADING!r} is one `- ` bullet")
        else:
            raise CodemapError(
                f"{where}: after the alias table only blank lines and {ALIAS_UNPLACED_HEADING!r} "
                "with its `- ` bullets may follow"
            )
    return entries, unplaced


def mapped_files(data: dict) -> int:
    return sum(len(c["files"]) for c in data["crates"].values())


