#!/usr/bin/env python3
"""Deterministic code map for Rust crates under `crates/`.

Scans every crate under `crates/` (except `crates/heed` and any `vendor/` tree)
and writes five generated artifacts an agent can read instead of walking the
tree:

  docs/CODEMAP.md                the orientation map (workspace + per-crate module tables)
  docs/codemap/<crate>.md        one FILE table per crate
  docs/codemap/codemap.json      the same data, machine-readable
  docs/codemap/BY-SPEC.md        each OF and ARCH id a leading doc block names -> its files
  docs/codemap/BY-CAPABILITY.md  reviewed capability aliases, then every module's purpose

The capability aliases are a reviewed input, scripts/codemap/capability_aliases.md: one
Markdown table (phrase | synonyms | paths | spec_ids | note), then an optional
`## Phrases not placed` list. A malformed alias file fails closed (CODEMAP-ERROR).
Every alias path must name a file in the repo (a mapped one shows its size bucket). A
path that names no file (moved or deleted) is marked on the page and printed as
`CODEMAP-ALIAS-MISSING: ...`, and the run fails: regenerating writes the map and exits 3,
so the main-only writer can still push the rest of the map before it reports the failure.

Modes:
  (default)   regenerate the artifacts in place; exit 3 after writing them when an
              alias path names no file in the repo
  --check     regenerate in memory and byte-compare with the committed artifacts;
              exit 1 with `CODEMAP-STALE: run python3 scripts/codemap/codemap.py`
              when they differ or an artifact is missing, and exit 1 on any
              `CODEMAP-ALIAS-MISSING`. Fails CLOSED (`CODEMAP-ERROR: ...`,
              exit 1) on an unreadable file, a malformed alias file or a scan
              that maps nothing.
  --sizes     print the live line-count table (crate . file . loc . test?) to
              stdout, sorted by size.  Never committed: line counts move on every
              edit, so they stay out of the artifacts.

Determinism rules for the artifacts: sorted paths, LF line endings, no
timestamps, no absolute paths, no line counts (size buckets only).

Stdlib only.  Runs from any cwd: the repo root is found with
`git rev-parse --show-toplevel` from the script's own directory, falling back to
the script's location (`scripts/codemap/codemap.py` -> repo root).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

PURPOSE_MAX = 110
GIANT_BAR = 800  # ratchet bar: a non-test file at or over this is a giant
BUCKETS = (("s", 300), ("m", 800), ("L", 1500))  # upper bounds, exclusive
BUCKET_TOP = "XL"
BUCKET_ORDER = {"s": 0, "m": 1, "L": 2, "XL": 3}
NOTABLE_MAX = 8

# Line-anchored on rustfmt-formatted source.  Qualifiers (`async`, `unsafe`,
# `const`, `extern "C"`) may sit between the visibility and the item kind.
PUB_RE = re.compile(
    r"^\s*pub(?P<vis>\([^)]*\))?\s+"
    r"(?:(?:async|unsafe|const|extern\s+\"[^\"]*\"|extern)\s+)*"
    r"(?P<kind>struct|enum|trait|fn|type|const|static|mod|use)\b"
    r"(?:\s+(?P<name>[A-Za-z_][A-Za-z0-9_]*))?"
)
IMPL_VAULT_RE = re.compile(r"^\s*impl\s+Vault\b")
SURFACE_ORDER = (
    "struct",
    "enum",
    "trait",
    "fn",
    "type",
    "const",
    "static",
    "mod",
    "re-export",
    "crate-vis",
)
NOTABLE_KINDS = {"struct", "enum", "trait"}

EXCLUDED_CRATES = {"heed"}
EXCLUDED_DIRS = {"vendor", "target"}
ROOT_FILES = {"lib.rs", "main.rs"}
MAP_PATH = PurePosixPath("docs/CODEMAP.md")
DIR_PATH = PurePosixPath("docs/codemap")
JSON_PATH = DIR_PATH / "codemap.json"
GENERATOR = "python3 scripts/codemap/codemap.py"
GENERATED_PAGE_NOTE = (
    f"Generated by `{GENERATOR}` — never edit by hand. Overview: [`../CODEMAP.md`](../CODEMAP.md)."
)
SPEC_PATH = DIR_PATH / "BY-SPEC.md"
CAPABILITY_PATH = DIR_PATH / "BY-CAPABILITY.md"
ALIASES_PATH = PurePosixPath("scripts/codemap/capability_aliases.md")
ALIAS_COLUMNS = ("phrase", "synonyms", "paths", "spec_ids", "note")
ALIAS_LIST_COLUMNS = ("synonyms", "paths", "spec_ids")
ALIAS_UNPLACED_HEADING = "## Phrases not placed"
TABLE_SEPARATOR_CELL_RE = re.compile(r":?-{3,}:?")
# Regenerate mode: the map is written, but an alias path names no file in the repo.
EXIT_ALIAS_MISSING = 3
# Canon spec ids: OF-<n> feature rows and ARCH-<nnnn> specs, each with an optional
# lowercase part suffix (OF-498c, ARCH-0023b); an ARCH id may carry one uppercase
# family prefix (CROSS-, ONEIRON-, EIRI-ARCH-0002). A three-digit ARCH number is
# padded to four (ARCH-023b is ARCH-0023b). FIX numbers are FIX-LIST rows, not spec
# ids, and are not indexed; nor are review, plan and issue ids (REVIEW-, ONE-, DEC-).
SPEC_ID_RE = re.compile(
    r"(?<![\w-])(?:(?P<of>OF-\d{3,}[a-z]?)"
    r"|(?P<prefix>[A-Z][A-Z0-9]*-)?ARCH-(?P<arch>\d{3,4})(?P<part>[a-z]?))(?![\w-])"
)
SPEC_ID_PARTS_RE = re.compile(r"^(?P<family>.*?)(?P<number>\d+)(?P<suffix>[a-z]?)$")


class CodemapError(Exception):
    """A fail-closed condition: reported as CODEMAP-ERROR, exit 1."""


