def is_test_path(rel: str) -> bool:
    """The ratchet's non-test definition (scripts/ratchet/check.sh), inverted.

    A path with a `tests/` or `tests_*/` directory component, or a file named
    `tests.rs`, `*_tests.rs` or `tests_*.rs`.
    """
    parts = PurePosixPath(rel).parts
    if any(part == "tests" or part.startswith("tests_") for part in parts[:-1]):
        return True
    name = parts[-1]
    return (
        name == "tests.rs"
        or name.endswith("_tests.rs")
        or (name.startswith("tests_") and name.endswith(".rs"))
    )


def bucket(loc: int) -> str:
    for label, upper in BUCKETS:
        if loc < upper:
            return label
    return BUCKET_TOP


def count_lines(data: bytes) -> int:
    """All lines, `wc -l` style plus one for an unterminated last line."""
    if not data:
        return 0
    n = data.count(b"\n")
    if not data.endswith(b"\n"):
        n += 1
    return n


def decode_lines(data: bytes) -> list[str]:
    text = data.decode("utf-8", errors="replace")
    return [line.rstrip("\r") for line in text.split("\n")]


SENTENCE_END_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z`\[(\"'])")
# A Rust `::` path is not a Markdown URL. Match only explicit symbol links,
# leaving external/relative links and shortcut/reference syntax unchanged.
# The first alternative protects examples inside inline code spans.
PURPOSE_LINK_RE = re.compile(
    r"(?P<code>`+).*?(?P=code)"
    r"|(?<![!\\])\[(?P<label>`[^`]+`|[^\[\]`]+)\]\("
    r"(?:::)?[A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)+\)"
)


def normalize_purpose_links(text: str) -> str:
    def replace(match: re.Match) -> str:
        label = match.group("label")
        return "`" + label.strip("`") + "`" if label is not None else match.group(0)

    return PURPOSE_LINK_RE.sub(replace, text)


def trim_purpose(text: str, limit: int = PURPOSE_MAX) -> str:
    """Collapse whitespace, keep the first sentence, drop the trailing period, cap the length."""
    text = " ".join(text.split())
    text = SENTENCE_END_RE.split(text, maxsplit=1)[0]
    text = text.rstrip(".").rstrip()
    if len(text) <= limit:
        return text
    cut = text[: limit - 1]
    space = cut.rfind(" ")
    if space >= limit // 2:
        cut = cut[:space]
    return cut.rstrip(" ,;:.") + "…"


def leading_doc_block(lines: list[str]) -> list[str]:
    """The bodies of the file's leading `//!` lines, every paragraph, untrimmed.

    Only the file head counts: blank lines, `//` comments and `#![...]`
    attributes before the first non-empty `//!` line are skipped, and the
    block ends at the first later line that is not `//!`, so an inline
    `mod x { //! ... }` deeper in the file is never mistaken for the file's
    own doc block.  An empty `//!` line is kept as `""`, a paragraph break.
    """
    block: list[str] = []
    started = False
    for line in lines:
        s = line.strip()
        if s.startswith("//!"):
            body = s[3:].strip()
            block.append(body)
            started = started or bool(body)
            continue
        if started:
            break
        if not s or s.startswith("//") or s.startswith("#!["):
            continue
        break
    return block


def extract_purpose(block: list[str]) -> str:
    """The first paragraph of the leading doc block, as one display line, or `—`.

    The paragraph's first sentence is kept, then capped at PURPOSE_MAX.
    """
    paragraph: list[str] = []
    for body in block:
        if body:
            paragraph.append(body)
        elif paragraph:
            break
    if not paragraph:
        return "—"
    return trim_purpose(normalize_purpose_links(" ".join(paragraph)))


def spec_sort_key(spec_id: str) -> tuple[str, int, str, str]:
    """Family, then number, then part suffix: `OF-99` before `OF-100`."""
    parts = SPEC_ID_PARTS_RE.match(spec_id)
    return (parts["family"], int(parts["number"]), parts["suffix"], spec_id)


def extract_spec_ids(block: list[str]) -> list[str]:
    """Every OF and ARCH id the whole leading doc block names, before any display trim."""
    ids: set[str] = set()
    for match in SPEC_ID_RE.finditer(" ".join(block)):
        if match["of"]:
            ids.add(match["of"])
        else:
            prefix = match["prefix"] or ""
            ids.add(f"{prefix}ARCH-{match['arch'].zfill(4)}{match['part']}")
    return sorted(ids, key=spec_sort_key)


def scan_file(path: Path, rel: str) -> dict:
    try:
        data = path.read_bytes()
    except OSError as error:
        raise CodemapError(f"unreadable file {rel}: {error}") from error
    lines = decode_lines(data)
    block = leading_doc_block(lines)
    loc = count_lines(data)
    counts: dict[str, int] = {}
    notable: set[str] = set()
    impl_vault = False
    for line in lines:
        if IMPL_VAULT_RE.match(line):
            impl_vault = True
        m = PUB_RE.match(line)
        if not m:
            continue
        if m.group("vis"):
            key = "crate-vis"
        elif m.group("kind") == "use":
            key = "re-export"
        else:
            key = m.group("kind")
        counts[key] = counts.get(key, 0) + 1
        if key in NOTABLE_KINDS and m.group("name"):
            notable.add(m.group("name"))
    return {
        "path": rel,
        "kind": "test" if is_test_path(rel) else "src",
        # FIX 8907: a generator writes its header on line 1 (`// Generated by ...`).
        "generated": bool(lines) and lines[0].startswith("// Generated"),
        "loc": loc,
        "bucket": bucket(loc),
        "surface": {k: counts[k] for k in SURFACE_ORDER if k in counts},
        "notable": sorted(notable),
        "purpose": extract_purpose(block),
        "spec_ids": extract_spec_ids(block),
        "impl_vault": impl_vault,
    }


