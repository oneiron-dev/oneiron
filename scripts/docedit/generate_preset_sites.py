#!/usr/bin/env python3
"""Generate the connection-site data used when a preset becomes a freeform."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "crates/oneiron-docedit/vendor/drawingml-presets/presetShapeDefinitions.xml"
OUTPUT = ROOT / "crates/oneiron-docedit/src/live/points/preset_sites/data.rs"
SOURCE_SHA256 = "2f7c868d857c1e3c4b5a6068759fe0e07d77ad58377a6618d1b02ba3507b6939"
A = "http://schemas.openxmlformats.org/drawingml/2006/main"
BUILT_IN = set("3cd4 3cd8 5cd8 7cd8 b cd2 cd4 cd8 h hc hd2 hd3 hd4 hd5 hd6 hd8 l ls r ss ssd16 ssd2 ssd32 ssd4 ssd6 ssd8 t vc w wd10 wd2 wd3 wd32 wd4 wd5 wd6 wd8".split())
OPS = set("*/ +- +/ ?: abs at2 cat2 cos max min mod pin sat2 sin sqrt tan val".split())


def integer(value):
    try:
        int(value)
        return True
    except ValueError:
        return False


def guides(shape, name):
    return [(gd.attrib["name"], gd.attrib["fmla"]) for gd in shape.findall(f"{{{A}}}{name}/{{{A}}}gd")]


def escape(value):
    return html.escape(value, quote=True)


def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("preset geometry source does not match its recorded ECMA digest")
    rows = []
    seen = {}
    excluded = []
    for shape in ET.fromstring(raw):
        name = shape.tag
        adjusts = guides(shape, "avLst")
        computed = guides(shape, "gdLst")
        connections = []
        for cxn in shape.findall(f"{{{A}}}cxnLst/{{{A}}}cxn"):
            pos = cxn.find(f"{{{A}}}pos")
            connections.append((cxn.attrib["ang"], pos.attrib["x"], pos.attrib["y"]))
        record = (adjusts, computed, connections)
        if name in seen:
            if record != seen[name]:
                raise ValueError(f"different duplicate preset definitions: {name}")
            continue
        seen[name] = record
        available = set(BUILT_IN)
        unresolved = set()
        for guide_name, formula in adjusts + computed:
            op, *args = formula.split()
            if op not in OPS:
                raise ValueError(f"unknown formula operator in {name}: {op}")
            unresolved.update(arg for arg in args if not integer(arg) and arg not in available)
            available.add(guide_name)
        for connection in connections:
            unresolved.update(arg for arg in connection if not integer(arg) and arg not in available)
        if unresolved:
            excluded.append((name, sorted(unresolved)))
            continue
        xml_guides = "".join(f'<a:gd name="{escape(n)}" fmla="{escape(f)}"/>' for n, f in computed)
        xml_connections = "".join(f'<a:cxn ang="{escape(ang)}"><a:pos x="{escape(x)}" y="{escape(y)}"/></a:cxn>' for ang, x, y in connections)
        names = sorted({n for n, _ in adjusts + computed})
        quoted = lambda s: json.dumps(s, ensure_ascii=False)
        av = "&[" + ", ".join(f"({quoted(n)}, {quoted(f)})" for n, f in adjusts) + "]"
        defined = "&[" + ", ".join(quoted(n) for n in names) + "]"
        rows.append("    Preset { name: " + quoted(name) + ", adjustments: " + av + ", guides: " + quoted(xml_guides) + ", connections: " + quoted(xml_connections) + ", names: " + defined + " },")
    header = "// Generated by scripts/docedit/generate_preset_sites.py; do not edit.\n// Copyright Ecma International. License: vendor/drawingml-presets/LICENSE.txt.\n// Source SHA-256: " + SOURCE_SHA256 + "\nuse super::Preset;\n\n#[rustfmt::skip]\npub(super) const PRESETS: &[Preset] = &[\n"
    return header + "\n".join(rows) + "\n];\n", excluded, len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report stale generated data without changing files")
    args = parser.parse_args()
    data, excluded, count = generate()
    if args.check:
        if OUTPUT.read_text() != data:
            raise SystemExit("preset connection-site data is stale")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(data)
    print(f"{count} preset definitions; excluded unresolved references: {excluded}")


if __name__ == "__main__":
    main()
