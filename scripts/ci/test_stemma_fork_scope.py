"""The vendored stemma fork's own unit tests in scoped CI.

Three parts, each driven without a real cargo:
  * scripts/ci/ci_scope.py: which changed paths set the `stemma_fork` output, and how the changed paths are
    read from git (a path git would quote, a file moved out of the fork);
  * scripts/ci/run_scoped.sh: which modes and scopes call the fork runner;
  * scripts/docedit/run_stemma_fork_unit_tests.sh: the lock it resolves from, the
    resolved lock it refuses, the cargo calls it makes and what it leaves behind.
The two shell scripts run in a disposable tree with a `cargo` that records its
calls; the fork runner's `cargo metadata` there writes the resolved lock the
case prepared.
"""

import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
from unittest import mock


CI = Path(__file__).resolve().parent
ROOT = CI.parents[1]
SCOPE_SCRIPT = CI / "ci_scope.py"
SCOPED_RUNNER = CI / "run_scoped.sh"
FORK_RUNNER = ROOT / "scripts/docedit/run_stemma_fork_unit_tests.sh"
WORKFLOW = ROOT / ".github/workflows/ci.yml"
FORK = "crates/oneiron-docedit/vendor"

_spec = importlib.util.spec_from_file_location("ci_scope", SCOPE_SCRIPT)
ci_scope = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ci_scope)

REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"

# Records each call; `metadata` leaves the case's resolved lock beside the manifest, as cargo's resolve does.
CARGO = """\
#!/usr/bin/env python3
import json, os, shutil, sys
from pathlib import Path

args = sys.argv[1:]
entry = {"args": args, "target_dir": os.environ.get("CARGO_TARGET_DIR"), "cwd": os.getcwd()}
if "--manifest-path" in args:
    manifest = Path(args[args.index("--manifest-path") + 1])
    lock = manifest.parent / "Cargo.lock"
    entry["lock_before"] = lock.read_text() if lock.exists() else None
with open(os.environ["STUB_LOG"], "a") as log:
    log.write(json.dumps(entry) + "\\n")
if args[0] == "metadata":
    shutil.copyfile(Path(os.environ["STUB_RESOLVED"]) / (manifest.parent.name + ".lock"), lock)
    print("{}")
elif args[0] == "test":
    sys.exit(int(os.environ.get("STUB_TEST_EXIT", "0")))
"""


def write_executable(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    path.chmod(0o755)


def lock_text(packages, unused_patches=()):
    """A lock file: (name, version, checksum) per package; a checksum of None makes a path package."""
    lines = ["# This file is automatically @generated by Cargo.", "version = 4", ""]
    for name, version, checksum in packages:
        lines += ["[[package]]", f'name = "{name}"', f'version = "{version}"']
        if checksum:
            lines += [f'source = "{REGISTRY}"', f'checksum = "{checksum}"']
        lines += ["dependencies = [", ' "serde",', "]", ""]
    for name, version in unused_patches:
        lines += ["[[patch.unused]]", f'name = "{name}"', f'version = "{version}"', ""]
    return "\n".join(lines)


class ScopeOutputTests(unittest.TestCase):
    def scope(self, *files):
        # The reverse-dependency map comes from `cargo metadata`; these cases do not read it.
        with mock.patch.object(ci_scope, "workspace_reverse_dependencies", return_value={}):
            return ci_scope.scope(list(files), False)

    def test_a_file_of_either_fork_package_sets_the_output(self):
        for path in (f"{FORK}/stemma-engine/src/import.rs", f"{FORK}/stemma-engine/tests/suite/main.rs",
                     f"{FORK}/stemma-engine/Cargo.toml", f"{FORK}/stemma-diff/src/lib.rs"):
            with self.subTest(path=path):
                out = self.scope(path)
                self.assertTrue(out["stemma_fork"])
                self.assertTrue(out["rust"])
                # The wrapper package's own tests still run for a fork change.
                self.assertEqual(out["packages"], ["oneiron-docedit"])

    def test_the_fork_runner_alone_sets_the_output_and_reaches_the_test_job(self):
        out = self.scope("scripts/docedit/run_stemma_fork_unit_tests.sh")
        self.assertTrue(out["stemma_fork"])
        self.assertTrue(out["rust"])
        self.assertTrue(out["pytools"])
        self.assertEqual(out["packages"], [])

    def test_other_paths_leave_the_output_unset(self):
        for path in ("crates/oneiron-docedit/src/lib.rs", "crates/oneiron-docedit/tests/contract.rs",
                     "crates/oneiron-docedit/PROVENANCE.md", f"{FORK}/drawingml-presets/presets.json",
                     f"{FORK}/stemma-engine-notes.md", "scripts/docedit/generate_preset_sites.py",
                     "crates/oneiron/src/lib.rs", "docs/ops/build-performance.md"):
            with self.subTest(path=path):
                self.assertFalse(self.scope(path)["stemma_fork"])

    def test_the_output_line_is_printed_and_written_for_the_workflow(self):
        with tempfile.TemporaryDirectory() as temp:
            written = Path(temp) / "github-output"
            env = dict(os.environ, GITHUB_OUTPUT=str(written))
            # --full reads no diff and no cargo metadata.
            result = subprocess.run([sys.executable, str(SCOPE_SCRIPT), "--full"], env=env, capture_output=True,
                                    text=True, check=True)
            self.assertIn("stemma_fork=false", result.stdout.splitlines())
            self.assertIn("stemma_fork=false", written.read_text().splitlines())

    def test_the_workflow_hands_the_output_to_the_test_job(self):
        text = WORKFLOW.read_text()
        self.assertIn("      stemma_fork: ${{ steps.scope.outputs.stemma_fork }}\n", text)
        self.assertIn("      SCOPE_STEMMA_FORK: ${{ needs.changes.outputs.stemma_fork }}\n", text)


class ChangedPathTests(unittest.TestCase):
    """ci_scope.changed_files over a disposable git repository, with git's default settings."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="oneiron-ci-scope-")
        self.addCleanup(self.temp.cleanup)
        self.repo = Path(self.temp.name).resolve()
        for patched in (mock.patch.dict(os.environ, {"GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}),
                        mock.patch.object(ci_scope, "ROOT", self.repo)):
            patched.start()
            self.addCleanup(patched.stop)
        self.git("init", "-q", "-b", "main")
        self.commit({f"{FORK}/stemma-engine/README.md": "the fork\n", "docs/notes.md": "notes\n"})

    def git(self, *args):
        subprocess.run(["git", "-c", "user.name=owen", "-c", "user.email=owen@example.com", "-c", "commit.gpgsign=false", *args],
                       cwd=self.repo, capture_output=True, text=True, check=True)

    def commit(self, files):
        for name, text in files.items():
            path = self.repo / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "change")

    def last_commit(self):
        files = ci_scope.changed_files("HEAD^1", "HEAD")
        with mock.patch.object(ci_scope, "workspace_reverse_dependencies", return_value={}):
            return files, ci_scope.scope(files, False)["stemma_fork"]

    def test_a_fork_path_git_would_quote_is_read_as_it_is(self):
        name = f"{FORK}/stemma-engine/testdata/m\u00e9tadata.json"
        self.commit({name: "{}\n"})
        files, fork = self.last_commit()
        self.assertEqual(files, [name])
        self.assertTrue(fork)

    def test_a_file_moved_out_of_the_fork_counts_at_the_path_it_left(self):
        self.git("mv", f"{FORK}/stemma-engine/README.md", "docs/stemma-readme.md")
        self.git("commit", "-q", "-m", "move")
        files, fork = self.last_commit()
        self.assertEqual(sorted(files), [f"{FORK}/stemma-engine/README.md", "docs/stemma-readme.md"])
        self.assertTrue(fork)


class ScopedRunnerTests(unittest.TestCase):
    """run_scoped.sh in a tree where cargo, the broker fixture and the fork runner only record their call."""

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="oneiron-scoped-runner-")
        self.addCleanup(self.temp.cleanup)
        self.tree = Path(self.temp.name).resolve()
        self.log = self.tree / "calls.log"
        for script in ("run_scoped.sh", "with-test-tmpdir.sh"):
            write_executable(self.tree / "scripts/ci" / script, (CI / script).read_text())
        record = '#!/bin/sh\necho "{name} $*" >> "$STUB_LOG"\n'
        write_executable(self.tree / "tools/cargo", record.format(name="cargo"))
        write_executable(self.tree / "scripts/ci/broker-fixture.sh", record.format(name="broker-fixture"))
        write_executable(self.tree / "scripts/docedit/run_stemma_fork_unit_tests.sh", record.format(name="fork-runner"))

    def run_mode(self, mode, **scope):
        env = {k: v for k, v in os.environ.items() if not k.startswith("SCOPE_")}
        env.update(scope, STUB_LOG=str(self.log), PATH=f"{self.tree / 'tools'}{os.pathsep}{os.environ['PATH']}")
        result = subprocess.run(["bash", "scripts/ci/run_scoped.sh", mode], cwd=self.tree, env=env,
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        calls = self.log.read_text().splitlines() if self.log.exists() else []
        return [call.split()[0] for call in calls], calls, result.stdout

    def test_a_scoped_test_run_calls_the_fork_runner_only_when_the_fork_changed(self):
        names, _, stdout = self.run_mode("test", SCOPE_FULL="false", SCOPE_STEMMA_FORK="true")
        self.assertEqual(names, ["fork-runner"])
        self.assertNotIn("nothing to test", stdout)

    def test_a_scoped_test_run_without_the_scope_does_not_call_it(self):
        for scope in ({}, {"SCOPE_STEMMA_FORK": "false"}, {"SCOPE_STEMMA_FORK": ""}):
            with self.subTest(scope=scope):
                names, _, stdout = self.run_mode("test", SCOPE_FULL="false", **scope)
                self.assertEqual(names, [])
                self.assertIn("no Rust package changed: nothing to test", stdout)

    def test_a_fork_change_runs_the_wrapper_package_and_then_the_fork_runner(self):
        names, calls, _ = self.run_mode("test", SCOPE_FULL="false", SCOPE_PACKAGES="oneiron-docedit",
                                        SCOPE_STEMMA_FORK="true")
        self.assertEqual(names, ["cargo", "fork-runner"])
        self.assertIn("nextest run --locked -p oneiron-docedit ", calls[0])

    def test_a_full_test_run_calls_the_fork_runner_whatever_the_scope_says(self):
        names, _, _ = self.run_mode("test", SCOPE_FULL="true")
        self.assertEqual(names, ["cargo", "cargo", "broker-fixture", "fork-runner"])

    def test_the_lint_and_featureless_modes_never_call_it(self):
        for mode in ("clippy", "featureless"):
            for full in ("false", "true"):
                with self.subTest(mode=mode, full=full):
                    self.log.unlink(missing_ok=True)
                    names, _, _ = self.run_mode(mode, SCOPE_FULL=full, SCOPE_STEMMA_FORK="true")
                    self.assertNotIn("fork-runner", names)


class ForkRunnerTests(unittest.TestCase):
    """run_stemma_fork_unit_tests.sh in a tree with a workspace lock, two empty fork manifests and a recording cargo."""

    WORKSPACE = [("oneiron-docedit", "0.1.0", None), ("stemma", "0.6.0", None), ("serde", "1.0.228", "aa11"),
                 ("zip", "0.6.6", "bb22"), ("zip", "8.6.0", "cc33"), ("tokio", "1.48.0", "dd44")]
    # What cargo's resolve keeps for a fork package: its own subset, and the fork's other path package.
    RESOLVED = [("stemma", "0.6.0", None), ("stemma-diff", "0.6.0", None), ("serde", "1.0.228", "aa11"),
                ("zip", "0.6.6", "bb22")]

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="oneiron-fork-runner-")
        self.addCleanup(self.temp.cleanup)
        self.tree = Path(self.temp.name).resolve() / "checkout"
        self.elsewhere = Path(self.temp.name).resolve() / "elsewhere"
        self.elsewhere.mkdir()
        self.log = self.tree.parent / "calls.log"
        self.resolved = self.tree.parent / "resolved"
        self.resolved.mkdir()
        self.runner = self.tree / "scripts/docedit/run_stemma_fork_unit_tests.sh"
        write_executable(self.runner, FORK_RUNNER.read_text())
        write_executable(self.tree.parent / "tools/cargo", CARGO)
        self.workspace_lock = lock_text(self.WORKSPACE)
        (self.tree / "Cargo.lock").write_text(self.workspace_lock)
        self.packages = ("stemma-engine", "stemma-diff")
        for package in self.packages:
            (self.tree / FORK / package).mkdir(parents=True)
            (self.tree / FORK / package / "Cargo.toml").write_text("")
            self.resolve(package, self.RESOLVED)

    def resolve(self, package, packages):
        text = lock_text(packages, unused_patches=[("lopdf", "0.44.0")])
        (self.resolved / f"{package}.lock").write_text(text)
        return text

    def run_runner(self, **extra):
        env = {k: v for k, v in os.environ.items() if k != "CARGO_TARGET_DIR"}
        env.update(extra, STUB_LOG=str(self.log), STUB_RESOLVED=str(self.resolved),
                   PATH=f"{self.tree.parent / 'tools'}{os.pathsep}{os.environ['PATH']}")
        # From a directory outside the checkout: the script finds the root by its own path.
        result = subprocess.run(["bash", str(self.runner)], cwd=self.elsewhere, env=env, capture_output=True, text=True)
        calls = [json.loads(line) for line in self.log.read_text().splitlines()] if self.log.exists() else []
        return result, calls

    def assert_no_lock_copy_left(self):
        for package in self.packages:
            self.assertFalse((self.tree / FORK / package / "Cargo.lock").exists(), package)

    def test_each_package_resolves_from_the_workspace_lock_and_tests_locked(self):
        resolved = self.resolve("stemma-engine", self.RESOLVED)
        result, calls = self.run_runner(CARGO_TARGET_DIR="/ci/target")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        manifests = [f"{FORK}/{package}/Cargo.toml" for package in self.packages]
        self.assertEqual([call["args"] for call in calls], [
            ["metadata", "--manifest-path", manifests[0], "--format-version", "1"],
            ["test", "--locked", "--manifest-path", manifests[0], "--lib"],
            ["metadata", "--manifest-path", manifests[1], "--format-version", "1"],
            ["test", "--locked", "--manifest-path", manifests[1], "--lib"],
        ])
        # The resolve starts from a copy of the workspace lock; the test run reads what the resolve left.
        self.assertEqual(calls[0]["lock_before"], self.workspace_lock)
        self.assertEqual(calls[1]["lock_before"], resolved)
        self.assertEqual(calls[2]["lock_before"], self.workspace_lock)
        for call in calls:
            self.assertEqual(call["cwd"], str(self.tree))
            self.assertEqual(call["target_dir"], "/ci/target/stemma-fork")
        self.assert_no_lock_copy_left()
        self.assertEqual((self.tree / "Cargo.lock").read_text(), self.workspace_lock)

    def test_without_a_target_dir_the_build_output_goes_under_the_checkout_target(self):
        result, calls = self.run_runner()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual({call["target_dir"] for call in calls}, {f"{self.tree}/target/stemma-fork"})

    def assert_refused(self, added, named):
        self.resolve("stemma-engine", self.RESOLVED + [added])
        result, calls = self.run_runner()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("the workspace's Cargo.lock does not hold", result.stderr)
        self.assertIn(named, result.stderr.splitlines())
        # Refused before anything is built: the one call is the first package's resolve.
        self.assertEqual([call["args"][0] for call in calls], ["metadata"])
        self.assert_no_lock_copy_left()

    def test_a_registry_package_the_workspace_lock_lacks_is_refused(self):
        self.assert_refused(("serde_test", "1.0.177", "ee55"), f"serde_test 1.0.177 {REGISTRY} ee55")

    def test_another_version_of_a_pinned_package_is_refused(self):
        self.assert_refused(("zip", "0.6.7", "ff66"), f"zip 0.6.7 {REGISTRY} ff66")

    def test_a_pinned_version_under_another_checksum_is_refused(self):
        self.assert_refused(("tokio", "1.48.0", "9999"), f"tokio 1.48.0 {REGISTRY} 9999")

    def test_a_path_package_other_than_the_fork_s_own_is_refused(self):
        self.assert_refused(("stemma-mcp", "0.6.0", None), "stemma-mcp 0.6.0 - -")

    def test_a_lock_file_already_beside_a_manifest_refuses_the_run_and_is_left_as_it_is(self):
        for package in self.packages:
            with self.subTest(package=package):
                self.log.unlink(missing_ok=True)
                mine = self.tree / FORK / package / "Cargo.lock"
                mine.write_text("mine\n")
                result, calls = self.run_runner()
                self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
                self.assertIn(f"{FORK}/{package}/Cargo.lock exists", result.stderr)
                # Refused before any cargo call, and before a copy is made beside the other manifest.
                self.assertEqual(calls, [])
                self.assertEqual(mine.read_text(), "mine\n")
                mine.unlink()
                self.assert_no_lock_copy_left()

    def test_a_failed_test_run_fails_the_script_and_still_removes_the_copies(self):
        result, calls = self.run_runner(STUB_TEST_EXIT="101")
        self.assertEqual(result.returncode, 101, result.stdout + result.stderr)
        self.assertEqual([call["args"][0] for call in calls], ["metadata", "test"])
        self.assert_no_lock_copy_left()


if __name__ == "__main__":
    unittest.main()
